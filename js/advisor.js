/* True if the error looks like the primary model is out of tokens/credits/
   rate-limited (as opposed to a bad key, bad request, etc.) — the case we
   fall back on. */
/* Resolves which Anthropic key the next call uses: the user's own key
   from Preferences if they saved one, else the app-wide key. */
async function _advPrimaryKey() {
  var own = '';
  try { own = (typeof getUserAnthropicKey === 'function') ? await getUserAnthropicKey() : ''; } catch (e) {}
  return own || _advisorApiKey;
}

/* A rejected own key is reported to the user rather than treated as a
   generic failure, so they know to fix it in Preferences. */
function _advCheckAuth(resp, key) {
  if ((resp.status === 401 || resp.status === 403) && key !== _advisorApiKey) throw new Error('OWN_KEY_INVALID');
}

var ADVISOR_OWN_KEY_INVALID_MSG = 'Anthropic rejected your API key. Update or remove it in ⚙️ Preferences.';

function _advIsTokenExhausted(err) {
  var msg = (err && err.message) || '';
  return msg === 'RATE_LIMIT' || /credit balance|insufficient_quota|quota exceeded|rate_limit|overloaded/i.test(msg);
}

/* FINOVA actions (js/finova-actions.js) — tool calls that propose adding
   entries, applied only after the user confirms a card in the chat. */
function _advActionsOn() {
  return typeof FinovaActions !== 'undefined';
}

/* Backup call — OpenRouter (OpenAI-compatible chat completions), only used
   when the primary model fails with a token/quota error and a backup key
   is set. Returns { text, calls }. With withTools, FINOVA's action tools
   are offered; if the backup model/route doesn't support tool calling the
   request is retried once without them (plain advice still works). */
async function _advBackupCall(messages, withTools) {
  var body = {
    model:      ADVISOR_BACKUP_MODEL,
    max_tokens: ADVISOR_BACKUP_MAX_TOKENS,
    reasoning:  { effort: 'low', exclude: true },
    messages:   [{ role: 'system', content: await _advSystemPrompt() }].concat(messages)
  };
  if (withTools && _advActionsOn()) body.tools = FinovaActions.openAITools();

  var resp = await fetch(ADVISOR_BACKUP_ENDPOINT, {
    method: 'POST',
    headers: {
      'Content-Type':  'application/json',
      'Authorization': 'Bearer ' + _advisorBackupApiKey,
      'HTTP-Referer':  location.origin,
      'X-Title':       'FinResolver FINOVA'
    },
    body: JSON.stringify(body)
  });

  if (!resp.ok) {
    var err = await resp.json().catch(function() { return {}; });
    var errMsg = (err.error && err.error.message) || 'BACKUP_API_ERROR';
    if (body.tools && /tool/i.test(errMsg)) return _advBackupCall(messages, false);
    throw new Error(errMsg);
  }
  var data = await resp.json();
  var choice = data.choices && data.choices[0];
  var out = _advActionsOn()
    ? FinovaActions.fromOpenAI(choice && choice.message)
    : { text: (choice && choice.message && choice.message.content) || '', calls: [] };
  /* Defense-in-depth: if the model got cut off before finishing
     (finish_reason "length" — it ran out of budget, typically mid
     chain-of-thought) treat it the same as an API error rather than
     returning a truncated/reasoning-in-progress mess as the "answer" — the
     caller's existing error-fallback UI is safer than leaking raw internal
     narration to the user. */
  if ((!out.text.trim() && !out.calls.length) || (choice && choice.finish_reason === 'length')) {
    throw new Error('BACKUP_TRUNCATED');
  }
  /* No "answered by backup AI" notice — the switch is meant to be invisible
     to the user, and baking any marker into the text would also get stored
     in _advisorHistory and replayed back to the model as prior context on
     later turns. */
  return out;
}

/* Low-level call — does NOT touch conversation history */
async function _advCallRaw(userContent) {
  try {
    return await _advCallPrimaryRaw(userContent);
  } catch (e) {
    if (_advIsTokenExhausted(e) && _advisorBackupApiKey) {
      return (await _advBackupCall([{ role: 'user', content: userContent }], false)).text;
    }
    throw e;
  }
}

async function _advCallPrimaryRaw(userContent) {
  var key  = await _advPrimaryKey();
  var resp = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'Content-Type':      'application/json',
      'x-api-key':         key,
      'anthropic-version': '2023-06-01',
      'anthropic-dangerous-direct-browser-access': 'true'
    },
    body: JSON.stringify({
      model:      ADVISOR_MODEL,
      max_tokens: ADVISOR_MAX_TOKENS,
      system:     await _advSystemPrompt(),
      messages:   [{ role: 'user', content: userContent }]
    })
  });

  _advCheckAuth(resp, key);
  if (resp.status === 429) throw new Error('RATE_LIMIT');
  if (!resp.ok) {
    var err = await resp.json().catch(function() { return {}; });
    throw new Error((err.error && err.error.message) || 'API_ERROR');
  }
  var data = await resp.json();
  return (data.content && data.content[0] && data.content[0].text) ? data.content[0].text : '';
}

/* Conversational call — maintains rolling history of last 6 messages.
   Falls back to the backup model (if configured) when the primary is out of
   tokens, reusing the same history so context isn't lost.
   Returns { text, calls } — calls are FINOVA action proposals. */
async function _advCallWithHistory(userContent) {
  /* Push user message (with snapshot injected) */
  _advisorHistory.push({ role: 'user', content: userContent });
  if (_advisorHistory.length > 6) _advisorHistory.shift();

  var answer;
  try {
    answer = await _advCallPrimaryHistory();
  } catch (e) {
    if (_advIsTokenExhausted(e) && _advisorBackupApiKey) {
      try {
        answer = await _advBackupCall(_advisorHistory, true);
      } catch (e2) {
        _advisorHistory.pop(); // remove the failed user message
        throw e2;
      }
    } else {
      _advisorHistory.pop(); // remove the failed user message
      throw e;
    }
  }

  /* History stays text-only: tool calls are stored as a plain-text note,
     so no dangling tool_use blocks are left behind when turns roll off. */
  var histText = answer.text;
  if (answer.calls.length) histText = (histText ? histText + '\n\n' : '') + FinovaActions.historyNote(answer.calls);
  _advisorHistory.push({ role: 'assistant', content: histText || '…' });
  if (_advisorHistory.length > 6) _advisorHistory.shift();

  return answer;
}

async function _advCallPrimaryHistory() {
  var body = {
    model:      ADVISOR_MODEL,
    max_tokens: ADVISOR_MAX_TOKENS,
    system:     await _advSystemPrompt(),
    messages:   _advisorHistory
  };
  if (_advActionsOn()) body.tools = FinovaActions.anthropicTools();

  var key  = await _advPrimaryKey();
  var resp = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'Content-Type':      'application/json',
      'x-api-key':         key,
      'anthropic-version': '2023-06-01',
      'anthropic-dangerous-direct-browser-access': 'true'
    },
    body: JSON.stringify(body)
  });

  _advCheckAuth(resp, key);
  if (resp.status === 429) throw new Error('RATE_LIMIT');
  if (!resp.ok) {
    var err = await resp.json().catch(function() { return {}; });
    throw new Error((err.error && err.error.message) || 'API_ERROR');
  }
  var data = await resp.json();
  if (_advActionsOn()) return FinovaActions.fromAnthropic(data.content);
  return { text: (data.content && data.content[0] && data.content[0].text) || '', calls: [] };
}

/* ─────────────────────────────────────────────────────────────
   4. PROACTIVE INSIGHTS (auto-generated on load)
───────────────────────────────────────────────────────────── */

/* Parse the model's insight labels out of the raw answer text. We scan the
   whole string for label occurrences rather than requiring each label to
   sit at the start of a line — models frequently prefix them with a bullet/
   number/markdown bold, or wrap the content onto a following line, and a
   strict line-start regex would silently drop those items (collapsing 3
   cards down to 1) or keep a label with nothing after it (an empty card). */
function _advParseInsights(answer) {
  /* The prompt asks the model to end with a "===END===" sentinel and nothing
     after it, specifically so the last item's slice (which otherwise runs to
     answer.length, unlike the first two items which are bounded by the next
     label) has a hard stop. Without it, models that self-check their answer
     inline (e.g. "Check word counts... Let's count.") leak that reasoning
     into the last card since nothing else bounds where it ends.
     A reasoning-style backup model will often restate the prompt's own
     instructions first (including the literal, quoted string "===END===" as
     part of that restatement) before ever giving a real answer — indexOf()
     used to grab that quoted, premature occurrence and truncate the *real*
     answer away entirely. Skip sentinel hits immediately preceded by a quote
     mark (same heuristic as the label filter below) and anchor to the LAST
     valid occurrence instead of the first. */
  var endRe = /===END===/g, endHits = [], em;
  while ((em = endRe.exec(answer))) {
    var beforeEnd = answer.slice(0, em.index).replace(/\s+$/, '');
    if (/["']$/.test(beforeEnd)) continue;
    endHits.push(em.index);
  }
  if (endHits.length) answer = answer.slice(0, endHits[endHits.length - 1]);

  var labelRe = /(⚠️|💡|📊)/g;
  var hits = [], m;
  while ((m = labelRe.exec(answer))) {
    /* If the model restates/quotes the prompt's format spec (e.g. `"⚠️ Risk:",
       "💡 Opportunity:"`) before giving its real answer, that quoted spec has
       labels too — but each is immediately preceded by a quote mark, which a
       genuine answer item never is. Skip those so the answer's real labels
       (further down the text) are used instead of the spec's. */
    var before = answer.slice(0, m.index).replace(/\s+$/, '');
    if (/["']$/.test(before)) continue;
    hits.push({ icon: m[1], index: m.index });
  }
  /* Even after the quote filter, a reasoning model's unquoted preamble
     ("...so we need one risk, one opportunity, one insight...") can still
     produce extra, non-quoted label-like hits before the real answer. The
     genuine 3 items are always the tail of the response, right before the
     sentinel, so anchor to the LAST 3 hits rather than the first 3. */
  if (hits.length > 3) hits = hits.slice(-3);

  var items = [];
  for (var i = 0; i < hits.length && items.length < 3; i++) {
    var start = hits[i].index;
    var end   = (i + 1 < hits.length) ? hits[i + 1].index : answer.length;

    /* The slice up to the next label often ends with that label's leftover
       bullet/number/markdown prefix (e.g. "- " or "**" or "2. ") sitting on
       its own trailing line — drop those noise-only trailing lines before
       stripping the current item's own prefix. */
    var lines = answer.slice(start, end).split('\n');
    while (lines.length > 1 && /^[\s*_.\-•\d)]*$/.test(lines[lines.length - 1])) lines.pop();

    var text = lines.join('\n')
      .replace(/^(⚠️|💡|📊)/, '')
      .replace(/^[\s*_.\-•\d)]+/, '')
      .replace(/^(Risk|Opportunity|Insight)\s*:?/i, '')
      .replace(/^[\s*_:\-]+/, '')
      .replace(/\s+/g, ' ')
      .trim();
    if (!text) continue;
    items.push({ icon: hits[i].icon, text: text });
  }
  return items;
}

