/* ── Chat transcript persistence ──
   The visible chat (last ADV_TRANSCRIPT_MAX messages) is kept per user in
   localStorage, encrypted with the same key as the month data. Only text is
   stored: action cards are never restored (they could be confirmed twice),
   their outcome is kept as a short note line instead. The model's own
   history (_advisorHistory) starts fresh each page load. */
var ADV_TRANSCRIPT_MAX = 20;
var _advTranscript     = [];
var _advTranscriptUid  = null;

function _advEmail() {
  return (typeof currentUser !== 'undefined' && currentUser) ? currentUser.email : null;
}

async function _advRestoreTranscript(uid) {
  if (_advTranscriptUid === uid) return;
  _advTranscriptUid = uid;
  _advTranscript    = [];
  _advisorHistory   = [];

  var chat = document.getElementById('advisorChatHistory');
  if (chat) chat.querySelectorAll('.adv-msg').forEach(function(el) { el.remove(); });

  var saved = null;
  try {
    var raw = localStorage.getItem('fr_finova_chat_' + uid);
    if (raw && typeof decryptFromStorage === 'function') saved = await decryptFromStorage(raw, _advEmail());
  } catch (e) {}
  if (_advTranscriptUid !== uid || !Array.isArray(saved)) return;

  saved = saved.filter(function(m) {
    return m && typeof m.text === 'string' && /^(user|assistant|note)$/.test(m.role);
  }).slice(-ADV_TRANSCRIPT_MAX);
  saved.forEach(function(m) { _advAppendMsg(m.role, m.text, true); });
  _advUpdateMode();
  /* Anything said while the decrypt was in flight goes after the restored lines. */
  _advTranscript = saved.concat(_advTranscript).slice(-ADV_TRANSCRIPT_MAX);
}

function _advRecord(role, text) {
  _advTranscript.push({ role: role, text: String(text || '').slice(0, 6000) });
  if (_advTranscript.length > ADV_TRANSCRIPT_MAX) _advTranscript = _advTranscript.slice(-ADV_TRANSCRIPT_MAX);
  var uid = _advTranscriptUid || _advUid(), copy = _advTranscript.slice();
  if (typeof encryptForStorage !== 'function') return;
  encryptForStorage(copy, _advEmail()).then(function(enc) {
    try { localStorage.setItem('fr_finova_chat_' + uid, enc); } catch (e) {}
  }).catch(function() {});
}

/* Warm every data source getFinancialSnapshot() reads from, regardless of
   which screens the user has already visited this session. Local loads
   (localStorage decrypt) always run. All steps are idempotent/safe to
   re-run even if the relevant tracker screen already loaded them. */
async function _advisorEnsureDataLoaded(uid) {
  var localJobs = [];
  if (typeof loadLoans === 'function')       localJobs.push(loadLoans());
  if (typeof loadInvestments === 'function') localJobs.push(loadInvestments());
  if (typeof loadLifestyle === 'function')   localJobs.push(loadLifestyle());
  if (typeof loadBuckets === 'function')     localJobs.push(loadBuckets());
  localJobs.push(_advWarmMonthCache(uid));
  await Promise.all(localJobs.map(function(p) { return Promise.resolve(p).catch(function() {}); }));

  /* No Firestore pull here: FINOVA is the home screen, so this runs on every
     app open. The login sync in sync.js (syncLoadData → syncPrefetchPastMonths
     → syncLoadConfig) already pulls everything and then calls
     finovaOnSyncLoaded(), which re-runs this with the fresh data. */

  /* Prices: once per session (and only once there are holdings to price) —
     returning to home shouldn't re-fetch every quote. */
  var hasHoldings = (typeof investmentsData !== 'undefined') && investmentsData && investmentsData.length > 0;
  if (_advPricesWarm || !hasHoldings) return;
  _advPricesWarm = true;

  /* Live investment prices (invQuoteCache for stocks/MF/ESOP, goldPriceCache
     for gold) are otherwise only fetched when the user visits the
     Investments tracker — if AI Advisor is opened first, getFinancialSnapshot()
     finds no cached quote for any holding and falls back to cost basis, so
     currentValue == invested and gainLossPct is always 0 regardless of the
     holding's actual performance.

     invFetchAllQuotes() fetches every ticker through a chain of CORS
     proxies, each with its own 6-8s timeout tried in sequence on failure —
     for a large portfolio (dozens of tickers) this can take a couple of
     minutes if the proxies are slow/rate-limited, which previously blocked
     insights from loading at all (they only start after this function
     resolves). Cap the wait so a slow/broken price fetch can never hold up
     insights — quotes keep populating invQuoteCache/goldPriceCache in the
     background past the cap for whatever chat/insights calls come after. */
  var priceJobs = [];
  if (typeof invFetchAllQuotes === 'function') priceJobs.push(invFetchAllQuotes());
  if (typeof fetchGoldPriceINR === 'function') priceJobs.push(fetchGoldPriceINR());
  if (priceJobs.length) {
    var pricesSettled = Promise.all(priceJobs.map(function(p) { return Promise.resolve(p).catch(function() {}); }));
    var priceTimeout   = new Promise(function(resolve) { setTimeout(resolve, 6000); });
    await Promise.race([pricesSettled, priceTimeout]);
  }
}

/* Decrypt any of the last 6 months already sitting in localStorage into
   _monthCache (module-scoped in data.js) so getCachedMonthData() can see
   them — this needs no network and works for guests/offline too. */
async function _advWarmMonthCache(uid) {
  if (typeof _monthCache === 'undefined' || typeof decryptFromStorage !== 'function') return;
  var now = new Date();
  var email = (typeof currentUser !== 'undefined' && currentUser) ? currentUser.email : null;
  var jobs = [];

  for (var i = 0; i < 6; i++) {
    var mm = now.getMonth() - i, yy = now.getFullYear();
    while (mm < 0) { mm += 12; yy--; }
    var cacheKey = uid + '_' + yy + '_' + mm;
    if (_monthCache.has(cacheKey)) continue;

    var raw = localStorage.getItem('fr_data_' + uid + '_' + yy + '_' + mm);
    if (!raw) continue;

    (function(cacheKey, raw) {
      jobs.push(
        decryptFromStorage(raw, email).then(function(parsed) {
          if (parsed) _monthCache.set(cacheKey, parsed);
        }).catch(function() {})
      );
    })(cacheKey, raw);
  }

  await Promise.all(jobs);
}

function _advisorHasData(uid) {
  var now = new Date();
  for (var i = 0; i <= 3; i++) {
    var m = now.getMonth() - i, y = now.getFullYear();
    if (m < 0) { m += 12; y--; }
    if (localStorage.getItem('fr_data_' + uid + '_' + y + '_' + m)) return true;
  }
  try {
    var inv  = localStorage.getItem('fr_investments_' + uid);
    var loan = localStorage.getItem('fr_loans_' + uid);
    if (inv  && JSON.parse(inv).length)  return true;
    if (loan && JSON.parse(loan).length) return true;
  } catch(e) {}
  return false;
}
