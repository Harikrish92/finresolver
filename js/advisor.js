function getFinancialSnapshot() {
  var uid = (typeof fbAuth !== 'undefined' && fbAuth && fbAuth.currentUser && fbAuth.currentUser.uid)
            ? fbAuth.currentUser.uid
            : (typeof currentUser !== 'undefined' && currentUser ? currentUser.uid : 'guest');

  var now = new Date();
  var yr  = now.getFullYear();
  var mo  = now.getMonth();

  /* ── Last 6 months trend (oldest → newest, only months with data) ── */
  var _sum = function(arr) {
    return (arr || []).reduce(function(a, e) { return a + Number(e.amount || 0); }, 0);
  };
  var months = [];
  for (var i = 0; i < 6; i++) {
    var mm = mo - i, yy = yr;
    while (mm < 0) { mm += 12; yy--; }
    months.push({ year: yy, month: mm });
  }
  months.reverse();

  var descMap = {}; // expense description → total amount (current month only)
  var monthlyTrend = [];
  months.forEach(function(mo2) {
    var d = (typeof getCachedMonthData === 'function')
            ? getCachedMonthData(uid, mo2.year, mo2.month) : null;
    if (!d) return;
    var inc = _sum(d.income), exp = _sum(d.expense);
    var savings = inc - exp;
    monthlyTrend.push({
      period:      ADVISOR_MONTH_NAMES[mo2.month] + ' ' + mo2.year,
      income:      Math.round(inc),
      expenses:    Math.round(exp),
      savings:     Math.round(savings),
      savingsRate: inc > 0 ? Math.round((savings / inc) * 100) : 0
    });
    if (mo2.year === yr && mo2.month === mo) {
      (d.expense || []).forEach(function(e) {
        var cat = (e.desc || 'Other').trim();
        descMap[cat] = (descMap[cat] || 0) + Number(e.amount || 0);
      });
    }
  });

  var trendInc = monthlyTrend.reduce(function(a, h) { return a + h.income;   }, 0);
  var trendExp = monthlyTrend.reduce(function(a, h) { return a + h.expenses; }, 0);
  var savingsRate = trendInc > 0 ? Math.round(((trendInc - trendExp) / trendInc) * 100) : 0;

  var topCategories = Object.entries(descMap)
    .sort(function(a, b) { return b[1] - a[1]; })
    .slice(0, 5)
    .map(function(pair) { return { name: pair[0], amount: Math.round(pair[1]) }; });

  /* ── Loans ── */
  /* Classic (v1) loan records store the rate/tenure under `interestRate` /
     `tenureMonths` (see js/loans.js) — not `rate` / `tenure` (that's the v2
     field naming, see v2/fr-data.js's _loanRate/_loanTenure). Reading
     loan.rate/loan.tenure directly here always evaluated to 0 for every
     Classic loan, regardless of what was actually entered in the Loans
     tracker. Fall back to rate/tenure too in case data ever comes from a v2
     schema (e.g. shared Firestore doc), mirroring v2's own adapter. */
  var _advLoanRate   = function(loan) { return Number(loan.interestRate !== undefined ? loan.interestRate : (loan.rate || 0)); };
  var _advLoanTenure = function(loan) { return Number(loan.tenureMonths !== undefined ? loan.tenureMonths : (loan.tenure || 0)); };

  var totalOutstanding = 0, totalEMI = 0, highestInterestLoan = null, loanList = [];
  try {
    var loans = (typeof loansData !== 'undefined') ? loansData : [];
    loans.forEach(function(loan) {
      if (loan.closed) return;
      var outstanding = Number(loan.principal || 0);
      (loan.payments || []).forEach(function(p) { outstanding -= Number(p.amount || 0); });
      if (typeof calcLoanStats === 'function') {
        try { outstanding = calcLoanStats(loan).outstanding; } catch(e2) {}
      }
      if (outstanding <= 0) return;
      totalOutstanding += outstanding;
      var loanRate = _advLoanRate(loan);
      var r   = loanRate / 100 / 12;
      var n   = _advLoanTenure(loan);
      var p   = Number(loan.principal || 0);
      var emi = (r > 0 && n > 0) ? p * r * Math.pow(1+r,n) / (Math.pow(1+r,n) - 1) : 0;
      totalEMI += emi;
      loanList.push({
        name:         loan.name,
        principal:    Math.round(p),
        outstanding:  Math.round(outstanding),
        rate:         loanRate,
        emi:          Math.round(emi),
        tenureMonths: n
      });
      if (!highestInterestLoan || loanRate > Number(highestInterestLoan.rate)) {
        highestInterestLoan = {
          name: loan.name,
          rate: loanRate,
          outstanding: Math.round(outstanding)
        };
      }
    });
  } catch(e) {}

  /* ── Investments ── */
  var totalInvested = 0, currentValue = 0;
  var catBreakdown = {};
  var holdingsList = [];
  try {
    var holdings = (typeof investmentsData !== 'undefined') ? investmentsData : [];
    holdings.forEach(function(h) {
      var cost = 0, val = 0, qty = 0, avgPx = 0, livePx = 0;
      if (h.category === 'Gold') {
        qty   = Number(h.grams || h.qty || 0);
        avgPx = Number(h.buyPricePerGram || h.avgPrice || 0);
        cost  = qty * avgPx;
        var liveG = (typeof goldPriceCache !== 'undefined' && goldPriceCache && goldPriceCache.pricePerGram)
                    ? goldPriceCache.pricePerGram : 0;
        livePx = liveG || avgPx;
        val = qty * livePx;
      } else if (h.category === 'RealEstate' || h.category === 'EPF') {
        cost   = Number(h.buyPrice || h.avgPrice || 0);
        val    = Number(h.curPrice || h.buyPrice || h.avgPrice || 0);
        livePx = Number(h.curPrice || 0);
      } else {
        qty   = Number(h.qty || 0);
        avgPx = Number(h.avgPrice || 0);
        cost  = qty * avgPx;
        var q = (typeof invQuoteCache !== 'undefined') && h.ticker && invQuoteCache[h.ticker];
        livePx = q ? (typeof toInr === 'function' ? toInr(q.price, q.currency) : q.price) : 0;
        val = livePx ? qty * livePx : cost;
      }
      totalInvested += cost;
      currentValue  += val;
      var cat = h.category || 'Others';
      catBreakdown[cat] = (catBreakdown[cat] || 0) + val;

      if (cost > 0 || val > 0) {
        var entry = {
          name:         h.name || h.ticker || 'Unknown',
          category:     cat === 'RealEstate' ? 'Real Estate' : cat,
          invested:     Math.round(cost),
          currentValue: Math.round(val),
          gainLoss:     Math.round(val - cost),
          gainLossPct:  cost > 0 ? Math.round(((val - cost) / cost) * 1000) / 10 : 0
        };
        if (h.ticker) entry.ticker       = h.ticker;
        if (h.isin)   entry.isin         = h.isin;
        if (qty)      entry.qty          = Math.round(qty * 100) / 100;
        if (avgPx)    entry.avgBuyPrice  = Math.round(avgPx);
        if (livePx)   entry.currentPrice = Math.round(livePx);
        var _hSrc = (typeof invGetHoldingSources === 'function')
                    ? invGetHoldingSources(h)
                    : (h.source && h.source !== 'manual' ? [h.source] : []);
        if (_hSrc.length) entry.brokers = _hSrc;
        holdingsList.push(entry);
      }
    });
  } catch(e) {}

  var portfolioBreakdown = Object.entries(catBreakdown)
    .sort(function(a, b) { return b[1] - a[1]; })
    .map(function(pair) { return { category: pair[0], value: Math.round(pair[1]) }; });

  /* ── Lifestyle Tracker (household goods + important dates) ── */
  var lifestyle = { totalItems: 0, totalValue: 0, items: [], events: [] };
  try {
    var goods  = (typeof lifestyleData !== 'undefined' && lifestyleData.goods)  ? lifestyleData.goods  : [];
    var events = (typeof lifestyleData !== 'undefined' && lifestyleData.events) ? lifestyleData.events : [];
    var today  = new Date(); today.setHours(0,0,0,0);

    var items = goods.map(function(g) {
      var warrantyExpiresInDays = null;
      if (g.purchaseDate && g.warrantyYears) {
        var exp = new Date(g.purchaseDate);
        exp.setFullYear(exp.getFullYear() + Number(g.warrantyYears));
        warrantyExpiresInDays = Math.round((exp - today) / 86400000);
      }
      var lifespanUsedPct = null;
      if (g.purchaseDate && g.expectedLifespan) {
        lifespanUsedPct = Math.round(((today - new Date(g.purchaseDate)) / (Number(g.expectedLifespan) * 365.25 * 86400000)) * 100);
      }
      return {
        name:                  g.name || 'Item',
        category:              g.category || 'Other',
        purchasePrice:         g.purchasePrice ? Math.round(g.purchasePrice) : 0,
        condition:             g.condition || null,
        warrantyExpiresInDays: warrantyExpiresInDays,
        lifespanUsedPct:       lifespanUsedPct
      };
    });

    lifestyle = {
      totalItems: items.length,
      totalValue: Math.round(items.reduce(function(a, i) { return a + i.purchasePrice; }, 0)),
      items:      items,
      events:     events.map(function(ev) {
        return { title: ev.title || 'Event', category: ev.category || null, date: ev.date || null, recurring: !!ev.recurring, notes: ev.notes || null };
      })
    };
  } catch(e) {}

  /* ── Portfolio Buckets (names are what FINOVA's add_bucket_entry matches on) ── */
  var portfolioBuckets = [];
  try {
    portfolioBuckets = ((typeof invBucketsData !== 'undefined') ? invBucketsData : []).map(function(b) {
      var recv = 0, prof = 0;
      (b.entries || []).forEach(function(e) {
        if (e.type === 'profit') prof += Number(e.amount) || 0; else recv += Number(e.amount) || 0;
      });
      return { name: b.name, totalReceived: Math.round(recv), totalProfit: Math.round(prof), entries: (b.entries || []).length };
    });
  } catch(e) {}

  /* ── Net worth ── */
  var curBal = (typeof getMonthBalance === 'function')
               ? getMonthBalance(uid, yr, mo) : 0;
  var netWorth = currentValue + Math.max(0, curBal) - totalOutstanding;

  /* ── Plain English summary ── */
  var srLabel = savingsRate >= 20 ? 'healthy' : savingsRate >= 10 ? 'moderate' : 'low';
  var summary = 'Net worth ' + _advFmt(netWorth) + ' with a ' + savingsRate + '% avg savings rate (' + srLabel +
    ') over the last ' + monthlyTrend.length + ' month(s). ' +
    'Portfolio value ' + _advFmt(currentValue) + ', loans outstanding ' + _advFmt(totalOutstanding) + '.';

  return {
    today: (typeof FinovaActions !== 'undefined') ? FinovaActions.todayISO() : now.toISOString().slice(0, 10),
    monthly: {
      last6Months:    monthlyTrend,
      topCategories:  topCategories,
      avgSavingsRate: savingsRate
    },
    loans: {
      totalOutstanding: Math.round(totalOutstanding),
      totalEMI:         Math.round(totalEMI),
      highestInterestLoan: highestInterestLoan,
      list: loanList
    },
    investments: {
      totalInvested:      Math.round(totalInvested),
      currentValue:       Math.round(currentValue),
      totalGainLoss:      Math.round(currentValue - totalInvested),
      portfolioBreakdown: portfolioBreakdown,
      holdings:           holdingsList
    },
    lifestyle: lifestyle,
    portfolioBuckets: portfolioBuckets,
    netWorth: Math.round(netWorth),
    summary:  summary
  };
}

/* Compact lakh/crore formatter for snapshot text */
function _advFmt(n) {
  if (typeof fmtCrore === 'function') return fmtCrore(n);
  var abs = Math.abs(n);
  var sign = n < 0 ? '-' : '';
  if (abs >= 1e7) return sign + '₹' + (abs / 1e7).toFixed(1) + 'Cr';
  if (abs >= 1e5) return sign + '₹' + (abs / 1e5).toFixed(1) + 'L';
  return sign + '₹' + Math.round(abs).toLocaleString('en-IN');
}

