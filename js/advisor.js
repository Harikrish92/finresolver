/* Re-check data, rebuild the snapshot/stat strip and (cached) insights.
   Serialised: a request that arrives mid-refresh runs once afterwards. */
async function _advRefreshHome() {
  if (_advHomeBusy) { _advHomeQueued = true; return; }
  _advHomeBusy = true;
  try {
    var uid = _advUid();
    await _advRestoreTranscript(uid);

    var hasData = _advisorHasData(uid);
    _advApplyDataState(hasData);
    if (!hasData) { _advHomeHasData = false; return; }

    /* Render what's already in memory straight away, then again once the
       local stores (and, once per session, live prices) are warmed. */
    _advisorSnapshot = getFinancialSnapshot();
    _advisorRenderCtxPanel(_advisorSnapshot);

    await _advisorEnsureDataLoaded(uid);
    _advisorSnapshot = getFinancialSnapshot();
    _advisorRenderCtxPanel(_advisorSnapshot);

    /* Daily-cached, so re-entering home doesn't cost an AI call. Data that
       only just arrived (first sync on a new device, or a new user's first
       confirmed entry) forces a fresh set. */
    var firstData = _advHomeHasData === false;
    _advHomeHasData = true;
    _advRequestInsights(firstData);
  } finally {
    _advHomeBusy = false;
    if (_advHomeQueued) { _advHomeQueued = false; _advRefreshHome(); }
  }
}

